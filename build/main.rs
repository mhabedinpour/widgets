mod codegen;
mod image;

use std::env;
use std::fs;
use std::path::Path;
use std::process::Command;

use littlefs2::{
    fs::{Allocation, Filesystem},
    path::PathBuf as LfsPathBuf,
};

fn main() {
    let out_dir = env::var("OUT_DIR").unwrap();
    let out_path = Path::new(&out_dir);

    generate_config(out_path);

    // Discover all services by scanning for traits annotated with @wasm.
    let services = codegen::parser::scan_services(Path::new("src"));

    // Parse WidgetEvent enum for event poll bindings.
    let events = codegen::parser::scan_events(Path::new("src/widget/mod.rs"));

    println!("cargo:rerun-if-changed=src");
    println!("cargo:rerun-if-changed=widgets/lib");

    let bindings_dir = Path::new("widgets/lib/bindings");
    fs::create_dir_all(bindings_dir).unwrap();

    codegen::typescript::generate_base_types(bindings_dir);

    for service in &services {
        codegen::rust_wasm::generate(service, out_path);

        let ts_out = format!("widgets/lib/bindings/{}.ts", service.name);
        codegen::typescript::generate(service, Path::new(&ts_out));
    }

    codegen::events::generate_rust(&events, out_path);
    codegen::events::generate_ts(&events, Path::new("widgets/lib/bindings/events.ts"));

    // Generated TS files now live in widgets/lib/, which is not scanned for widget
    // compilation, so no skip list is needed.
    build_widgets(&[]);

    build_admin_ui();
    build_fs_image();

    linker_be_nice();

    // make sure linkall.x is the last linker script (otherwise might cause problems with flip-link)
    println!("cargo:rustc-link-arg=-Tlinkall.x");
}

fn build_widgets(skip: &[&str]) {
    let widgets_dir = Path::new("widgets");
    if !widgets_dir.exists() {
        return;
    }

    let root = env::current_dir().unwrap();
    let dest_path = root.join("fs-image-content/widgets");
    fs::create_dir_all(&dest_path).unwrap();

    let entries = fs::read_dir(widgets_dir).unwrap();

    // Check if node/npm are available, add /opt/homebrew/bin if needed
    let path = env::var("PATH").unwrap_or_default();
    let new_path = if path.contains("/opt/homebrew/bin") {
        path
    } else {
        format!("{}:/opt/homebrew/bin", path)
    };

    for entry in entries {
        let entry = entry.unwrap();
        let path = entry.path();
        if path.extension().map_or(false, |ext| ext == "ts") {
            let name = path.file_stem().unwrap().to_str().unwrap();
            // Skip files generated by the codegen step
            if skip.contains(&name) {
                continue;
            }
            let wasm_path = dest_path.join(format!("{}.wasm", name));

            println!("cargo:rerun-if-changed={}", path.display());

            let status = Command::new("npx")
                .env("PATH", &new_path)
                .current_dir(widgets_dir)
                .arg("asc")
                .arg(path.file_name().unwrap())
                .arg("-o")
                .arg(&wasm_path)
                .arg("-Osize")
                .arg("--optimizeLevel")
                .arg("3")
                .arg("--shrinkLevel")
                .arg("2")
                .arg("--runtime")
                .arg("incremental")
                .status()
                .expect("failed to execute asc");

            if !status.success() {
                panic!("failed to compile widget {}", name);
            }
        }
    }
}

fn build_admin_ui() {
    let admin_ui_dir = Path::new("admin-ui");
    if !admin_ui_dir.exists() {
        return;
    }

    println!("cargo:rerun-if-changed=admin-ui/src");
    println!("cargo:rerun-if-changed=admin-ui/public");
    println!("cargo:rerun-if-changed=admin-ui/index.html");
    println!("cargo:rerun-if-changed=admin-ui/package.json");
    println!("cargo:rerun-if-changed=admin-ui/package-lock.json");
    println!("cargo:rerun-if-changed=admin-ui/vite.config.ts");
    println!("cargo:rerun-if-changed=admin-ui/tsconfig.json");
    println!("cargo:rerun-if-changed=admin-ui/tsconfig.app.json");
    println!("cargo:rerun-if-changed=admin-ui/tsconfig.node.json");

    let path = env::var("PATH").unwrap_or_default();
    let new_path = if path.contains("/opt/homebrew/bin") {
        path
    } else {
        format!("{}:/opt/homebrew/bin", path)
    };

    let npm_cmd = if cfg!(target_os = "windows") {
        "npm.cmd"
    } else {
        "npm"
    };

    if !admin_ui_dir.join("node_modules").exists() {
        let install_status = Command::new(npm_cmd)
            .env("PATH", &new_path)
            .current_dir(admin_ui_dir)
            .arg("ci")
            .status()
            .expect("failed to execute npm code ci for admin-ui");

        if !install_status.success() {
            panic!("failed to install dependencies for admin-ui");
        }
    }

    let status = Command::new(npm_cmd)
        .env("PATH", &new_path)
        .current_dir(admin_ui_dir)
        .arg("run")
        .arg("build")
        .status()
        .expect("failed to execute npm run build for admin-ui");

    if !status.success() {
        panic!("failed to build admin-ui");
    }

    let dist_index = admin_ui_dir.join("dist").join("index.html");
    let dest_dir = Path::new("fs-image-content/admin");
    fs::create_dir_all(dest_dir).unwrap();
    let dest_index = dest_dir.join("index.html");

    fs::copy(&dist_index, &dest_index).unwrap_or_else(|err| {
        panic!(
            "failed to copy {} to {}: {}",
            dist_index.display(),
            dest_index.display(),
            err
        )
    });
}

fn build_fs_image() {
    let fs_image_content = Path::new("fs-image-content");
    if !fs_image_content.exists() {
        fs::create_dir_all(fs_image_content).unwrap();
    }

    println!("cargo:rerun-if-changed=fs-image-content");
    println!("cargo:rerun-if-changed=src/storage/mod.rs");
    println!("cargo:rerun-if-changed=config.json");

    fs::copy("config.json", fs_image_content.join("config.json")).unwrap();

    let image_size = image::BLOCK_SIZE * image::BLOCK_COUNT;
    let image_path = Path::new("target/littlefs.bin");

    // Ensure target directory exists
    if let Some(parent) = image_path.parent() {
        fs::create_dir_all(parent).unwrap();
    }

    let mut storage = image::RamStorage {
        data: vec![0xff; image_size],
    };

    let mut alloc = Allocation::new();

    Filesystem::format(&mut storage).expect("failed to format littlefs");

    Filesystem::mount(&mut alloc, &mut storage)
        .and_then(|lfs| {
            image::add_files_recursive(&lfs, fs_image_content, &LfsPathBuf::try_from("/").unwrap())
        })
        .expect("failed to populate littlefs image");

    fs::write(image_path, storage.data).expect("failed to write littlefs image");

    println!(
        "cargo:info=Successfully created littlefs image ({} bytes) at {}",
        image_size,
        image_path.display()
    );
}

fn generate_config(out_path: &Path) {
    println!("cargo:rerun-if-changed=config.json");

    let config_str = fs::read_to_string("config.json").unwrap_or_else(|_| {
        panic!(
            "config.json not found — copy config.example.json to config.json and fill in your settings"
        )
    });
    let cfg: serde_json::Value =
        serde_json::from_str(&config_str).expect("config.json is not valid JSON");

    let mut out = String::from("// Auto-generated from config.json — do not edit.\n\n");

    // Hub75 pin macro — expands to a Hub75Pins16 { ... } expression.
    // Types are resolved at the call site (all needed imports are in main.rs).
    let pin_fields = [
        "red1", "grn1", "blu1", "red2", "grn2", "blu2", "addr0", "addr1", "addr2", "addr3",
        "addr4", "blank", "clock", "latch",
    ];
    out.push_str("macro_rules! hub75_pins {\n");
    out.push_str("    ($p:ident) => {\n");
    out.push_str("        Hub75Pins16 {\n");
    for field in &pin_fields {
        let num = cfg["display"]["pins"][field]
            .as_u64()
            .unwrap_or_else(|| panic!("config.json: display.pins.{} is missing", field));
        out.push_str(&format!(
            "            {}: $p.GPIO{}.degrade(),\n",
            field, num
        ));
    }
    out.push_str("        }\n");
    out.push_str("    };\n");
    out.push_str("}\n");

    fs::write(out_path.join("config.rs"), &out).unwrap();
}

fn linker_be_nice() {
    let args: Vec<String> = env::args().collect();
    if args.len() > 1 {
        let kind = &args[1];
        let what = &args[2];

        match kind.as_str() {
            "undefined-symbol" => match what.as_str() {
                what if what.starts_with("_defmt_") => {
                    eprintln!();
                    eprintln!(
                        "💡 `defmt` not found - make sure `defmt.x` is added as a linker script and you have included `use defmt_rtt as _;`"
                    );
                    eprintln!();
                }
                "_stack_start" => {
                    eprintln!();
                    eprintln!("💡 Is the linker script `linkall.x` missing?");
                    eprintln!();
                }
                what if what.starts_with("esp_rtos_") => {
                    eprintln!();
                    eprintln!(
                        "💡 `esp-radio` has no scheduler enabled. Make sure you have initialized `esp-rtos` or provided an external scheduler."
                    );
                    eprintln!();
                }
                "embedded_test_linker_file_not_added_to_rustflags" => {
                    eprintln!();
                    eprintln!(
                        "💡 `embedded-test` not found - make sure `embedded-test.x` is added as a linker script for tests"
                    );
                    eprintln!();
                }
                "free"
                | "malloc"
                | "calloc"
                | "get_free_internal_heap_size"
                | "malloc_internal"
                | "realloc_internal"
                | "calloc_internal"
                | "free_internal" => {
                    eprintln!();
                    eprintln!(
                        "💡 Did you forget the `esp-alloc` dependency or didn't enable the `compat` feature on it?"
                    );
                    eprintln!();
                }
                _ => (),
            },
            // we don't have anything helpful for "missing-lib" yet
            _ => {
                std::process::exit(1);
            }
        }

        std::process::exit(0);
    }

    println!(
        "cargo:rustc-link-arg=-Wl,--error-handling-script={}",
        env::current_exe().unwrap().display()
    );
}
