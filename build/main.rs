mod codegen;

use std::env;
use std::fs;
use std::path::Path;
use std::process::Command;

/// Describes one service to generate bindings for.
struct ServiceConfig {
    /// Service name (also used as the WasmCtx accessor method name and TS factory class name).
    name: &'static str,
    /// Source directory containing annotated `*Data` structs.
    src_dir: &'static str,
    /// Path to write the generated TypeScript library, or `None` to skip TS generation.
    ts_out: Option<&'static str>,
    /// Prefix stripped from WASM function names to derive TS method/builder names.
    /// e.g. `"draw_"` turns `draw_rect` → method `rect` / `RectBuilder`.
    ts_fn_prefix: &'static str,
    /// Whether to emit shared base types (Color, Point, Size, Rect) in the TS output.
    ts_base_types: bool,
}

/// All services to generate. Add new services here — no other file needs to change.
const SERVICES: &[ServiceConfig] = &[
    ServiceConfig {
        name: "drawer",
        src_dir: "src/drawer",
        ts_out: Some("widgets/drawer.ts"),
        ts_fn_prefix: "draw_",
        ts_base_types: true,
    },
    // ServiceConfig { name: "http", src_dir: "src/http", ts_out: None, ts_fn_prefix: "http_", ts_base_types: false },
];

fn main() {
    let out_dir = env::var("OUT_DIR").unwrap();
    let out_path = Path::new(&out_dir);

    for svc in SERVICES {
        println!("cargo:rerun-if-changed={}", svc.src_dir);

        let service = codegen::parser::parse_service(svc.name, Path::new(svc.src_dir));
        codegen::rust_wasm::generate(&service, out_path);

        if let Some(ts_out) = svc.ts_out {
            let ts_config = codegen::typescript::TsConfig {
                fn_prefix: svc.ts_fn_prefix,
                emit_base_types: svc.ts_base_types,
            };
            codegen::typescript::generate(&service, Path::new(ts_out), &ts_config);
        }
    }

    // Names of TS files generated by the codegen step (excluded from widget compilation).
    let generated_ts: Vec<&str> = SERVICES
        .iter()
        .filter_map(|s| s.ts_out)
        .filter_map(|p| Path::new(p).file_stem().and_then(|s| s.to_str()))
        .collect();

    // Compile AssemblyScript widgets to WASM and embed them.
    build_widgets(&generated_ts);

    linker_be_nice();

    // make sure linkall.x is the last linker script (otherwise might cause problems with flip-link)
    println!("cargo:rustc-link-arg=-Tlinkall.x");
}

fn build_widgets(skip: &[&str]) {
    let widgets_dir = Path::new("widgets");
    if !widgets_dir.exists() {
        return;
    }

    let out_dir = env::var("OUT_DIR").unwrap();
    let dest_path = Path::new(&out_dir).join("widgets");
    fs::create_dir_all(&dest_path).unwrap();

    let entries = fs::read_dir(widgets_dir).unwrap();

    // Check if node/npm are available, add /opt/homebrew/bin if needed
    let path = env::var("PATH").unwrap_or_default();
    let new_path = if path.contains("/opt/homebrew/bin") {
        path
    } else {
        format!("{}:/opt/homebrew/bin", path)
    };

    for entry in entries {
        let entry = entry.unwrap();
        let path = entry.path();
        if path.extension().map_or(false, |ext| ext == "ts") {
            let name = path.file_stem().unwrap().to_str().unwrap();
            // Skip files generated by the codegen step
            if skip.contains(&name) {
                continue;
            }
            let wasm_path = dest_path.join(format!("{}.wasm", name));

            println!("cargo:rerun-if-changed={}", path.display());

            let status = Command::new("npx")
                .env("PATH", &new_path)
                .current_dir(widgets_dir)
                .arg("asc")
                .arg(path.file_name().unwrap())
                .arg("-o")
                .arg(&wasm_path)
                .arg("-Osize")
                .arg("--optimizeLevel")
                .arg("3")
                .arg("--shrinkLevel")
                .arg("2")
                .arg("--runtime")
                .arg("incremental")
                .status()
                .expect("failed to execute asc");

            if !status.success() {
                panic!("failed to compile widget {}", name);
            }
        }
    }

    // Generate a mod.rs file to include all widgets
    let mut mod_contents = String::new();
    let entries = fs::read_dir(widgets_dir).unwrap();
    for entry in entries {
        let entry = entry.unwrap();
        let path = entry.path();
        if path.extension().map_or(false, |ext| ext == "ts") {
            let name = path.file_stem().unwrap().to_str().unwrap();
            if name == "drawer" {
                continue;
            }
            mod_contents.push_str(&format!(
                "pub const {}: &[u8] = include_bytes!(\"{}.wasm\");\n",
                name.to_uppercase(),
                name
            ));
        }
    }
    fs::write(dest_path.join("mod.rs"), mod_contents).unwrap();
}

fn linker_be_nice() {
    let args: Vec<String> = std::env::args().collect();
    if args.len() > 1 {
        let kind = &args[1];
        let what = &args[2];

        match kind.as_str() {
            "undefined-symbol" => match what.as_str() {
                what if what.starts_with("_defmt_") => {
                    eprintln!();
                    eprintln!(
                        "💡 `defmt` not found - make sure `defmt.x` is added as a linker script and you have included `use defmt_rtt as _;`"
                    );
                    eprintln!();
                }
                "_stack_start" => {
                    eprintln!();
                    eprintln!("💡 Is the linker script `linkall.x` missing?");
                    eprintln!();
                }
                what if what.starts_with("esp_rtos_") => {
                    eprintln!();
                    eprintln!(
                        "💡 `esp-radio` has no scheduler enabled. Make sure you have initialized `esp-rtos` or provided an external scheduler."
                    );
                    eprintln!();
                }
                "embedded_test_linker_file_not_added_to_rustflags" => {
                    eprintln!();
                    eprintln!(
                        "💡 `embedded-test` not found - make sure `embedded-test.x` is added as a linker script for tests"
                    );
                    eprintln!();
                }
                "free"
                | "malloc"
                | "calloc"
                | "get_free_internal_heap_size"
                | "malloc_internal"
                | "realloc_internal"
                | "calloc_internal"
                | "free_internal" => {
                    eprintln!();
                    eprintln!(
                        "💡 Did you forget the `esp-alloc` dependency or didn't enable the `compat` feature on it?"
                    );
                    eprintln!();
                }
                _ => (),
            },
            // we don't have anything helpful for "missing-lib" yet
            _ => {
                std::process::exit(1);
            }
        }

        std::process::exit(0);
    }

    println!(
        "cargo:rustc-link-arg=-Wl,--error-handling-script={}",
        std::env::current_exe().unwrap().display()
    );
}
