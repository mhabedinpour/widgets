use std::path::Path;

use crate::codegen::model::{BindingDef, ServiceDef};
use crate::codegen::render;

/// Generate `{out_dir}/{service_name}_wasm_bindings.rs`.
pub fn generate(service: &ServiceDef, out_dir: &Path) {
    let module_struct = format!("{}Module", capitalize(&service.name));
    let out_path = out_dir.join(format!("{}_wasm_bindings.rs", service.name));

    let bindings: String = service.bindings.iter()
        .map(|b| render_binding(b, &service.name))
        .collect::<Vec<_>>()
        .join("");

    let buf = render(
        r#"// AUTO-GENERATED by build/codegen/rust_wasm.rs — DO NOT EDIT.
// Source: src/%name%/ @wasm annotations

impl HostModule for %module% {
    fn name(&self) -> &str { "%name%" }

    fn register(
        &self,
        linker: &mut Linker<WasmCtx>,
        store: &mut Store<WasmCtx>,
    ) -> Result<(), wasmi::Error> {
%bindings%
        Ok(())
    }
}
"#,
        &[
            ("name",     &service.name),
            ("module",   &module_struct),
            ("bindings", &bindings),
        ],
    );

    std::fs::write(&out_path, &buf)
        .unwrap_or_else(|e| panic!("cannot write {}: {e}", out_path.display()));
}

/// Map an ABI scalar type to the Rust type used in the host closure
/// signature. Pointers ("usize") are u32 on wasm32.
fn rust_abi_ty(ty: &str) -> &'static str {
    match ty {
        "u64" => "u64",
        "i32" => "i32",
        "i64" => "i64",
        _ => "u32",
    }
}

fn render_binding(binding: &BindingDef, service_name: &str) -> String {
    let mut all_params: Vec<String> = Vec::new();
    let mut preamble = String::new();

    for field in &binding.fields {
        for a in &field.expansion.abi {
            all_params.push(format!("{}: {}", a.name, rust_abi_ty(a.ty)));
        }
        preamble.push_str(&field.expansion.abi_to_rust.preamble);
    }

    let params = all_params.join(", ");
    let sep = if params.is_empty() { "" } else { ", " };
    // Closures always return Result so field converters can trap the guest
    // (via `Err(wasmi::Error)`) on invalid input instead of panicking.
    let ret_sig = match &binding.return_expansion {
        Some(re) => format!(" -> Result<{}, wasmi::Error>", rust_abi_ty(re.abi[0].ty)),
        None => " -> Result<(), wasmi::Error>".to_string(),
    };
    let data_construction = render_data_construction(binding, service_name);
    let call_stmt = render_call_stmt(binding, service_name);

    render(
        r#"
        // --- %func% ---
        linker.define(
            self.name(),
            "%func%",
            wasmi::Func::wrap(
                &mut *store,
                |mut caller: Caller<'_, WasmCtx>%sep%%params%|%ret_sig% {
%preamble%%data_construction%                    %call_stmt%
                },
            ),
        )?;"#,
        &[
            ("func",              &binding.executor_method),
            ("sep",               sep),
            ("params",            &params),
            ("ret_sig",           &ret_sig),
            ("preamble",          &preamble),
            ("data_construction", &data_construction),
            ("call_stmt",         &call_stmt),
        ],
    )
}

fn render_data_construction(binding: &BindingDef, service_name: &str) -> String {
    if binding.fields.is_empty() {
        return String::new();
    }
    let field_lines: String = binding.fields.iter()
        .map(|f| format!("                        {}: {},\n", f.name, f.expansion.abi_to_rust.exprs[0]))
        .collect();
    render(
        "                    let data = crate::%svc%::%dtype% {\n%fields%                    };\n",
        &[("svc", service_name), ("dtype", binding.data_type.as_deref().unwrap()), ("fields", &field_lines)],
    )
}

fn render_call_stmt(binding: &BindingDef, service_name: &str) -> String {
    let call = if binding.fields.is_empty() {
        format!("caller.data_mut().ctx.as_mut().unwrap().{service_name}.{}()", binding.executor_method)
    } else {
        format!("caller.data_mut().ctx.as_mut().unwrap().{service_name}.{}(data)", binding.executor_method)
    };
    // Service calls run on the SRAM heap; everything else in the binding
    // (field decoding, the guest itself) stays on the PSRAM heap.
    match &binding.return_expansion {
        Some(re) => {
            let to_abi = render(&re.rust_to_abi.exprs[0], &[("v", "__ret")]);
            format!(
                "crate::use_sram_heap();\n                    \
                 let __ret = {call};\n                    \
                 crate::use_psram_heap();\n                    \
                 Ok({to_abi})"
            )
        }
        None => format!(
            "crate::use_sram_heap();\n                    \
             {call};\n                    \
             crate::use_psram_heap();\n                    \
             Ok(())"
        ),
    }
}

fn capitalize(s: &str) -> String {
    let mut c = s.chars();
    match c.next() {
        None => String::new(),
        Some(f) => f.to_uppercase().collect::<String>() + c.as_str(),
    }
}
