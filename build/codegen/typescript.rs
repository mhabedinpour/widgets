use std::path::Path;

use crate::codegen::model::ServiceDef;
use crate::codegen::render;

/// Write the shared base types to `{widgets_dir}/types.ts`.
pub fn generate_base_types(widgets_dir: &Path) {
    let out_path = widgets_dir.join("types.ts");
    std::fs::write(&out_path, BASE_TYPES)
        .unwrap_or_else(|e| panic!("cannot write {}: {e}", out_path.display()));
}

/// Generate the TypeScript library file (e.g. `widgets/lib/drawer.ts`).
pub fn generate(service: &ServiceDef, out_path: &Path) {
    let wasm_module = &service.name;
    let factory_class = capitalize(wasm_module);

    let wasm_decls: String = service.bindings.iter()
        .map(|b| render_wasm_decl(b, wasm_module))
        .collect();

    let factory_methods: String = service.bindings.iter()
        .map(|b| render_factory_method(b))
        .collect();

    let builder_classes: String = service.bindings.iter()
        .map(|b| render_builder_class(b, service))
        .collect();

    let buf = render(
        r#"// Automatically generated by build/codegen/typescript.rs. DO NOT EDIT.
import { Color, Point, Size, Rect, Duration, StrokeAlignment, Font, TextAlignment, Baseline } from "./types";

declare namespace %wasm_module% {
%wasm_decls%}

export class %factory_class% {
%factory_methods%}

%builder_classes%"#,
        &[
            ("wasm_module",     wasm_module),
            ("factory_class",   &factory_class),
            ("wasm_decls",      &wasm_decls),
            ("factory_methods", &factory_methods),
            ("builder_classes", &builder_classes),
        ],
    );

    std::fs::write(out_path, &buf)
        .unwrap_or_else(|e| panic!("cannot write {}: {e}", out_path.display()));
}

fn render_wasm_decl(binding: &crate::codegen::model::BindingDef, wasm_module: &str) -> String {
    let params: Vec<String> = binding.fields.iter()
        .flat_map(|f| f.expansion.abi.iter())
        .map(|a| format!("{}: {}", a.name, a.ty))
        .collect();
    let ret_ts = match &binding.return_expansion {
        Some(re) => re.abi[0].ty,
        None => "void",
    };
    render(
        "  @external(\"%mod%\", \"%func%\")\n  function %func%(%params%): %ret%;\n",
        &[
            ("mod",    wasm_module),
            ("func",   &binding.executor_method),
            ("params", &params.join(", ")),
            ("ret",    ret_ts),
        ],
    )
}

fn render_factory_method(
    binding: &crate::codegen::model::BindingDef,
) -> String {
    let builder_class = format!("{}Builder", capitalize(&binding.builder_name));
    let method = &binding.builder_name;

    let (params, args): (Vec<String>, Vec<String>) = binding.fields.iter()
        .filter(|f| f.expansion.ta_default.is_none()) // required fields only
        .map(|f| (format!("{}: {}", f.name, f.expansion.ta_type), f.name.clone()))
        .unzip();

    let sep = if args.is_empty() { "" } else { ", " };
    render(
        "  %method%(%params%): %builder% {\n    return new %builder%(this%sep%%args%);\n  }\n",
        &[
            ("method",  method),
            ("params",  &params.join(", ")),
            ("builder", &builder_class),
            ("sep",     sep),
            ("args",    &args.join(", ")),
        ],
    )
}

fn render_builder_class(
    binding: &crate::codegen::model::BindingDef,
    service: &ServiceDef,
) -> String {
    let builder_class = format!("{}Builder", capitalize(&binding.builder_name));
    let factory_class = capitalize(&service.name);
    let svc_field = &service.name;
    let wasm_module = &service.name;

    let mut private_fields = String::new();
    let mut ctor_param_list: Vec<String> = Vec::new();
    let mut ctor_assigns = String::new();
    let mut all_call_args: Vec<String> = Vec::new();
    let mut str_preamble = String::new();

    for f in &binding.fields {
        let (name, ty) = (&f.name, &f.expansion.ta_type);
        match &f.expansion.ta_default {
            // Optional: field with default, set via setter.
            Some(d) => private_fields.push_str(&format!("  private _{name}: {ty} = {d};\n")),
            // Required: field set via constructor.
            None => {
                private_fields.push_str(&format!("  private _{name}: {ty};\n"));
                ctor_param_list.push(format!("{name}: {ty}"));
                ctor_assigns.push_str(&format!("    this._{name} = {name};\n"));
            }
        }
        // TA serializes: TS value → ABI scalars.
        let value = format!("this._{}", f.name);
        if !f.expansion.ts_to_abi.preamble.is_empty() {
            str_preamble.push_str(&render(&f.expansion.ts_to_abi.preamble, &[("v", &value)]));
        }
        for e in &f.expansion.ts_to_abi.exprs {
            all_call_args.push(render(e, &[("v", &value)]));
        }
    }

    // Setter methods — optional fields only; required fields go through the constructor.
    let setters: String = binding.fields.iter()
        .filter(|f| f.expansion.ta_default.is_some())
        .map(|f| {
            let ts_type = &f.expansion.ta_type;
            let setter = f.setter_name.as_deref().unwrap_or(&f.name);
            let param  = format!("{setter}: {ts_type}");
            let assign = format!("this._{} = {setter};", f.name);
            render(
                "  %setter%(%param%): %builder% {\n    %assign%\n    return this;\n  }\n",
                &[
                    ("setter",  setter),
                    ("param",   &param),
                    ("builder", &builder_class),
                    ("assign",  &assign),
                ],
            )
        })
        .collect();

    let call = format!("{wasm_module}.{}({})", binding.executor_method, all_call_args.join(", "));
    // TA deserializes the return value: ABI scalar → TS value.
    let (execute_line, ret_type) = match &binding.return_expansion {
        Some(re) => (
            format!("    const {} = {call};\n    return {};\n", re.abi[0].name, re.abi_to_ts.exprs[0]),
            re.ta_type.as_str(),
        ),
        None => (format!("    {call};\n"), "void"),
    };

    let ctor_sep = if ctor_param_list.is_empty() { "" } else { ", " };
    let setters_block = if setters.is_empty() {
        String::new()
    } else {
        format!("\n{}", setters.trim_end_matches('\n'))
    };

    render(
        r#"export class %builder% {
%private_fields%  private %svc%: %factory%;

  constructor(%svc%: %factory%%ctor_sep%%ctor_params%) {
    this.%svc% = %svc%;
%ctor_assigns%  }%setters%

  execute(): %ret_type% {
%str_preamble%%execute_line%  }
}

"#,
        &[
            ("builder",        &builder_class),
            ("private_fields", &private_fields),
            ("svc",            svc_field),
            ("factory",        &factory_class),
            ("ctor_sep",       ctor_sep),
            ("ctor_params",    &ctor_param_list.join(", ")),
            ("ctor_assigns",   &ctor_assigns),
            ("setters",        &setters_block),
            ("ret_type",       ret_type),
            ("str_preamble",   &str_preamble),
            ("execute_line",   &execute_line),
        ],
    )
}

fn capitalize(s: &str) -> String {
    let mut chars = s.chars();
    match chars.next() {
        None => String::new(),
        Some(f) => f.to_uppercase().collect::<String>() + chars.as_str(),
    }
}

