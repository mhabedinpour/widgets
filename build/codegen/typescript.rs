use std::fmt::Write as _;
use std::path::Path;

use crate::codegen::model::{FieldType, ServiceDef};
use crate::codegen::type_map::{expand_ts, expand_wasm};

/// TypeScript-specific generation options.
pub struct TsConfig<'a> {
    /// Prefix stripped from WASM function names to derive TS method/builder names.
    /// e.g. `"draw_"` turns `draw_rect` → method `rect` / `RectBuilder`.
    /// Use `""` to keep the full function name.
    pub fn_prefix: &'a str,
    /// Whether to emit the shared base types (Color, Point, Size, Rect).
    /// Set to `false` for services that don't use these types (e.g. HTTP).
    pub emit_base_types: bool,
}

/// Generate the TypeScript library file (e.g. `widgets/drawer.ts`).
pub fn generate(service: &ServiceDef, out_path: &Path, config: &TsConfig<'_>) {
    let mut buf = String::new();

    writeln!(
        buf,
        "// Automatically generated by build/codegen/typescript.rs. DO NOT EDIT."
    )
    .unwrap();
    writeln!(buf).unwrap();

    let wasm_module = service
        .bindings
        .first()
        .map(|b| b.wasm_module.as_str())
        .unwrap_or("env");

    // 1. WASM function declarations — all fields flattened via expand_wasm
    writeln!(buf, "declare namespace {wasm_module} {{").unwrap();
    for binding in &service.bindings {
        let mut params: Vec<String> = Vec::new();
        for field in &binding.fields {
            let exp = expand_wasm(&field.name, &field.ty);
            for param in &exp.params {
                let ts_type = if param.ends_with("_ptr") || param.ends_with("_len") {
                    "usize"
                } else {
                    "u32"
                };
                params.push(format!("{param}: {ts_type}"));
            }
        }
        writeln!(
            buf,
            "  @external(\"{}\", \"{}\")\n  function {}({}): void;",
            binding.wasm_module,
            binding.wasm_fn,
            binding.wasm_fn,
            params.join(", ")
        )
        .unwrap();
    }
    writeln!(buf, "}}").unwrap();
    writeln!(buf).unwrap();

    // 2. Base type classes (optional)
    if config.emit_base_types {
        buf.push_str(BASE_TYPES);
    }

    // 3. Service factory class — name derived from service name (e.g. "drawer" → "Drawer")
    let factory_class = capitalize(&service.name);
    writeln!(buf, "export class {factory_class} {{").unwrap();
    for binding in &service.bindings {
        let method_name = ts_method_name(&binding.wasm_fn, config.fn_prefix);
        let builder_name = builder_class_name(&binding.wasm_fn, config.fn_prefix);

        // Factory method signature: only required fields as flat params
        let mut factory_params: Vec<String> = Vec::new();
        let mut factory_args: Vec<String> = Vec::new();
        for field in &binding.fields {
            if !field.required {
                continue;
            }
            let exp = expand_ts(&field.name, &field.ty, true, field.default.as_deref());
            for (pname, ptype) in &exp.ctor_params {
                factory_params.push(format!("{pname}: {ptype}"));
                factory_args.push(pname.clone());
            }
        }

        let sep = if factory_args.is_empty() { "" } else { ", " };
        writeln!(
            buf,
            "  {method_name}({}): {builder_name} {{",
            factory_params.join(", ")
        )
        .unwrap();
        writeln!(
            buf,
            "    return new {builder_name}(this{sep}{});",
            factory_args.join(", ")
        )
        .unwrap();
        writeln!(buf, "  }}").unwrap();
    }
    writeln!(buf, "}}").unwrap();
    writeln!(buf).unwrap();

    // 4. One builder class per binding
    for binding in &service.bindings {
        let builder_name = builder_class_name(&binding.wasm_fn, config.fn_prefix);

        writeln!(buf, "export class {builder_name} {{").unwrap();

        // Gather all field info
        struct FieldInfo {
            name: String,
            ty: FieldType,
            required: bool,
            default: Option<String>,
            setter_name: Option<String>,
        }
        let fields: Vec<FieldInfo> = binding
            .fields
            .iter()
            .map(|f| FieldInfo {
                name: f.name.clone(),
                ty: f.ty.clone(),
                required: f.required,
                default: f.default.clone(),
                setter_name: f.setter_name.clone(),
            })
            .collect();

        // Emit private field declarations
        let mut ctor_params: Vec<String> = Vec::new();
        let mut ctor_assigns: Vec<String> = Vec::new();
        let mut all_call_args: Vec<String> = Vec::new();
        let mut str_field_names: Vec<String> = Vec::new();

        for f in &fields {
            let exp = expand_ts(&f.name, &f.ty, f.required, f.default.as_deref());

            // Private fields
            for (fname, ftype, default) in &exp.fields {
                match default {
                    Some(d) => writeln!(buf, "  private {fname}: {ftype} = {d};").unwrap(),
                    None => writeln!(buf, "  private {fname}: {ftype};").unwrap(),
                }
            }

            // Constructor params + assignments for required fields
            if f.required {
                for (pname, ptype) in &exp.ctor_params {
                    ctor_params.push(format!("{pname}: {ptype}"));
                }
                match f.ty {
                    FieldType::Rect => {
                        ctor_assigns.push("this._x = x;".to_string());
                        ctor_assigns.push("this._y = y;".to_string());
                        ctor_assigns.push("this._w = w;".to_string());
                        ctor_assigns.push("this._h = h;".to_string());
                    }
                    FieldType::Point => {
                        ctor_assigns.push(format!("this._{n}_x = {n}_x;", n = f.name));
                        ctor_assigns.push(format!("this._{n}_y = {n}_y;", n = f.name));
                    }
                    FieldType::Str => {
                        ctor_assigns.push(format!("this._{} = {};", f.name, f.name));
                        str_field_names.push(f.name.clone());
                    }
                    _ => {
                        // Single ctor param → single private field
                        if let (Some((pname, _)), Some((fname, _, _))) =
                            (exp.ctor_params.first(), exp.fields.first())
                        {
                            ctor_assigns.push(format!("this.{fname} = {pname};"));
                        }
                    }
                }
            }

            all_call_args.extend(exp.call_args.clone());
        }

        // Reference back to the service factory (e.g. "drawer: Drawer", "http: Http")
        let svc_field = &service.name;
        writeln!(buf, "  private {svc_field}: {factory_class};").unwrap();

        // Constructor
        let sep = if ctor_params.is_empty() { "" } else { ", " };
        writeln!(
            buf,
            "  constructor({svc_field}: {factory_class}{sep}{}) {{",
            ctor_params.join(", ")
        )
        .unwrap();
        writeln!(buf, "    this.{svc_field} = {svc_field};").unwrap();
        for assign in &ctor_assigns {
            writeln!(buf, "    {assign}").unwrap();
        }
        writeln!(buf, "  }}").unwrap();

        // Setter methods for optional fields
        for f in &fields {
            if f.required {
                continue;
            }
            let setter = f.setter_name.as_deref().unwrap_or(&f.name);
            match f.ty {
                FieldType::Color => {
                    writeln!(buf, "  {setter}(color: Color): {builder_name} {{").unwrap();
                    writeln!(buf, "    this._{} = color;", f.name).unwrap();
                    writeln!(buf, "    return this;").unwrap();
                    writeln!(buf, "  }}").unwrap();
                }
                FieldType::Bool => {
                    writeln!(buf, "  {setter}(value: bool): {builder_name} {{").unwrap();
                    writeln!(buf, "    this._{} = value;", f.name).unwrap();
                    writeln!(buf, "    return this;").unwrap();
                    writeln!(buf, "  }}").unwrap();
                }
                FieldType::U32 => {
                    writeln!(buf, "  {setter}({setter}: u32): {builder_name} {{").unwrap();
                    writeln!(buf, "    this._{} = {setter};", f.name).unwrap();
                    writeln!(buf, "    return this;").unwrap();
                    writeln!(buf, "  }}").unwrap();
                }
                _ => {} // Point/Rect/Str as optional are uncommon; skip for now
            }
        }

        // draw() method
        writeln!(buf, "  draw(): void {{").unwrap();
        // Str encoding preamble
        for sn in &str_field_names {
            writeln!(
                buf,
                "    const __{sn}_buf = String.UTF8.encode(this._{sn});"
            )
            .unwrap();
            writeln!(buf, "    const __{sn}_ptr = changetype<usize>(__{sn}_buf);").unwrap();
            writeln!(buf, "    const __{sn}_len = __{sn}_buf.byteLength;").unwrap();
        }
        writeln!(
            buf,
            "    {wasm_module}.{}({});",
            binding.wasm_fn,
            all_call_args.join(", ")
        )
        .unwrap();
        writeln!(buf, "  }}").unwrap();

        writeln!(buf, "}}").unwrap();
        writeln!(buf).unwrap();
    }

    std::fs::write(out_path, &buf)
        .unwrap_or_else(|e| panic!("cannot write {}: {e}", out_path.display()));
}

/// Strip the service fn prefix to get the factory method name.
/// e.g. `"draw_rect"` with prefix `"draw_"` → `"rect"`.
fn ts_method_name(wasm_fn: &str, fn_prefix: &str) -> String {
    wasm_fn
        .strip_prefix(fn_prefix)
        .unwrap_or(wasm_fn)
        .to_string()
}

/// Derive the builder class name from a WASM function name.
/// e.g. `"draw_rect"` with prefix `"draw_"` → `"RectBuilder"`.
fn builder_class_name(wasm_fn: &str, fn_prefix: &str) -> String {
    let base = wasm_fn.strip_prefix(fn_prefix).unwrap_or(wasm_fn);
    format!("{}Builder", capitalize(base))
}

fn capitalize(s: &str) -> String {
    let mut chars = s.chars();
    match chars.next() {
        None => String::new(),
        Some(f) => f.to_uppercase().collect::<String>() + chars.as_str(),
    }
}

// Static base types that don't depend on the service model
const BASE_TYPES: &str = r#"export class Color {
  r: u8; g: u8; b: u8;
  constructor(r: u8, g: u8, b: u8) { this.r = r; this.g = g; this.b = b; }
  static readonly WHITE: Color = new Color(255, 255, 255);
  static readonly BLACK: Color = new Color(0, 0, 0);
}

export class Point {
  x: u32; y: u32;
  constructor(x: u32, y: u32) { this.x = x; this.y = y; }
}

export class Size {
  width: u32; height: u32;
  constructor(width: u32, height: u32) { this.width = width; this.height = height; }
}

export class Rect {
  x: u32; y: u32; width: u32; height: u32;
  constructor(x: u32, y: u32, width: u32, height: u32) { this.x = x; this.y = y; this.width = width; this.height = height; }
}

"#;
