use std::fmt::Write as _;
use std::path::Path;

use crate::codegen::model::{FieldType, ServiceDef};
use crate::codegen::type_map::{expand_ts, expand_wasm, ts_return_type};

/// Write the shared base types to `{widgets_dir}/types.ts`.
pub fn generate_base_types(widgets_dir: &Path) {
    let out_path = widgets_dir.join("types.ts");
    std::fs::write(&out_path, BASE_TYPES)
        .unwrap_or_else(|e| panic!("cannot write {}: {e}", out_path.display()));
}

/// Generate the TypeScript library file (e.g. `widgets/drawer.ts`).
pub fn generate(service: &ServiceDef, out_path: &Path) {
    let mut buf = String::new();

    writeln!(
        buf,
        "// Automatically generated by build/codegen/typescript.rs. DO NOT EDIT."
    )
    .unwrap();
    writeln!(
        buf,
        "import {{ Color, Point, Size, Rect, Duration }} from \"./types\";"
    )
    .unwrap();
    writeln!(buf).unwrap();

    let wasm_module = &service.name;

    // 1. WASM function declarations — all fields flattened via expand_wasm
    writeln!(buf, "declare namespace {wasm_module} {{").unwrap();
    for binding in &service.bindings {
        let mut params: Vec<String> = Vec::new();
        for field in &binding.fields {
            let exp = expand_wasm(&field.name, &field.ty);
            for param in &exp.params {
                let ts_type = if param.ends_with("_ptr") || param.ends_with("_len") {
                    "usize"
                } else if field.ty == FieldType::Duration {
                    "u64"
                } else {
                    "u32"
                };
                params.push(format!("{param}: {ts_type}"));
            }
        }
        let ret_ts = match &binding.return_type {
            Some(rt) => ts_return_type(rt),
            None => "void",
        };
        writeln!(
            buf,
            "  @external(\"{wasm_module}\", \"{}\")\n  function {}({}): {};",
            binding.executor_method,
            binding.executor_method,
            params.join(", "),
            ret_ts,
        )
        .unwrap();
    }
    writeln!(buf, "}}").unwrap();
    writeln!(buf).unwrap();

    // 2. Service factory class — name derived from service name (e.g. "drawer" → "Drawer")
    let factory_class = capitalize(&service.name);
    writeln!(buf, "export class {factory_class} {{").unwrap();
    for binding in &service.bindings {
        let method_name = &binding.builder_name;
        let builder_class = format!("{}Builder", capitalize(&binding.builder_name));

        // Factory method signature: only required fields as flat params
        let mut factory_params: Vec<String> = Vec::new();
        let mut factory_args: Vec<String> = Vec::new();
        for field in &binding.fields {
            if !field.required {
                continue;
            }
            let exp = expand_ts(&field.name, &field.ty, true, field.default.as_deref());
            for (pname, ptype) in &exp.ctor_params {
                factory_params.push(format!("{pname}: {ptype}"));
                factory_args.push(pname.clone());
            }
        }

        let sep = if factory_args.is_empty() { "" } else { ", " };
        writeln!(
            buf,
            "  {method_name}({}): {builder_class} {{",
            factory_params.join(", ")
        )
        .unwrap();
        writeln!(
            buf,
            "    return new {builder_class}(this{sep}{});",
            factory_args.join(", ")
        )
        .unwrap();
        writeln!(buf, "  }}").unwrap();
    }
    writeln!(buf, "}}").unwrap();
    writeln!(buf).unwrap();

    // 3. One builder class per binding
    for binding in &service.bindings {
        let builder_class = format!("{}Builder", capitalize(&binding.builder_name));

        writeln!(buf, "export class {builder_class} {{").unwrap();

        // Gather all field info
        struct FieldInfo {
            name: String,
            ty: FieldType,
            required: bool,
            default: Option<String>,
            setter_name: Option<String>,
        }
        let fields: Vec<FieldInfo> = binding
            .fields
            .iter()
            .map(|f| FieldInfo {
                name: f.name.clone(),
                ty: f.ty.clone(),
                required: f.required,
                default: f.default.clone(),
                setter_name: f.setter_name.clone(),
            })
            .collect();

        // Emit private field declarations
        let mut ctor_params: Vec<String> = Vec::new();
        let mut ctor_assigns: Vec<String> = Vec::new();
        let mut all_call_args: Vec<String> = Vec::new();
        let mut str_field_names: Vec<String> = Vec::new();

        for f in &fields {
            let exp = expand_ts(&f.name, &f.ty, f.required, f.default.as_deref());

            // Private fields
            for (fname, ftype, default) in &exp.fields {
                match default {
                    Some(d) => writeln!(buf, "  private {fname}: {ftype} = {d};").unwrap(),
                    None => writeln!(buf, "  private {fname}: {ftype};").unwrap(),
                }
            }

            // Constructor params + assignments for required fields
            if f.required {
                for (pname, ptype) in &exp.ctor_params {
                    ctor_params.push(format!("{pname}: {ptype}"));
                }
                match f.ty {
                    FieldType::Str => {
                        ctor_assigns.push(format!("this._{} = {};", f.name, f.name));
                        str_field_names.push(f.name.clone());
                    }
                    _ => {
                        // Single ctor param → single private field
                        if let (Some((pname, _)), Some((fname, _, _))) =
                            (exp.ctor_params.first(), exp.fields.first())
                        {
                            ctor_assigns.push(format!("this.{fname} = {pname};"));
                        }
                    }
                }
            }

            all_call_args.extend(exp.call_args.clone());
        }

        // Reference back to the service factory (e.g. "drawer: Drawer", "http: Http")
        let svc_field = &service.name;
        writeln!(buf, "  private {svc_field}: {factory_class};").unwrap();

        // Constructor
        let sep = if ctor_params.is_empty() { "" } else { ", " };
        writeln!(
            buf,
            "  constructor({svc_field}: {factory_class}{sep}{}) {{",
            ctor_params.join(", ")
        )
        .unwrap();
        writeln!(buf, "    this.{svc_field} = {svc_field};").unwrap();
        for assign in &ctor_assigns {
            writeln!(buf, "    {assign}").unwrap();
        }
        writeln!(buf, "  }}").unwrap();

        // Setter methods for optional fields
        for f in &fields {
            if f.required {
                continue;
            }
            let setter = f.setter_name.as_deref().unwrap_or(&f.name);
            match f.ty {
                FieldType::Color => {
                    writeln!(buf, "  {setter}(color: Color): {builder_class} {{").unwrap();
                    writeln!(buf, "    this._{} = color;", f.name).unwrap();
                    writeln!(buf, "    return this;").unwrap();
                    writeln!(buf, "  }}").unwrap();
                }
                FieldType::Bool => {
                    writeln!(buf, "  {setter}(value: bool): {builder_class} {{").unwrap();
                    writeln!(buf, "    this._{} = value;", f.name).unwrap();
                    writeln!(buf, "    return this;").unwrap();
                    writeln!(buf, "  }}").unwrap();
                }
                FieldType::U32 => {
                    writeln!(buf, "  {setter}({setter}: u32): {builder_class} {{").unwrap();
                    writeln!(buf, "    this._{} = {setter};", f.name).unwrap();
                    writeln!(buf, "    return this;").unwrap();
                    writeln!(buf, "  }}").unwrap();
                }
                FieldType::Duration => {
                    writeln!(buf, "  {setter}({setter}: Duration): {builder_class} {{").unwrap();
                    writeln!(buf, "    this._{} = {setter};", f.name).unwrap();
                    writeln!(buf, "    return this;").unwrap();
                    writeln!(buf, "  }}").unwrap();
                }
                _ => {} // Point/Rect/Str as optional are uncommon; skip for now
            }
        }

        // execute() method — generic name that works for any service
        let ret_type = match &binding.return_type {
            Some(rt) => ts_return_type(rt),
            None => "void",
        };
        writeln!(buf, "  execute(): {ret_type} {{").unwrap();
        // Str encoding preamble
        for sn in &str_field_names {
            writeln!(
                buf,
                "    const __{sn}_buf = String.UTF8.encode(this._{sn});"
            )
            .unwrap();
            writeln!(buf, "    const __{sn}_ptr = changetype<usize>(__{sn}_buf);").unwrap();
            writeln!(buf, "    const __{sn}_len = __{sn}_buf.byteLength;").unwrap();
        }
        let call_stmt = format!(
            "{wasm_module}.{}({});",
            binding.executor_method,
            all_call_args.join(", ")
        );
        if binding.return_type.is_some() {
            writeln!(buf, "    return {call_stmt}").unwrap();
        } else {
            writeln!(buf, "    {call_stmt}").unwrap();
        }
        writeln!(buf, "  }}").unwrap();

        writeln!(buf, "}}").unwrap();
        writeln!(buf).unwrap();
    }

    std::fs::write(out_path, &buf)
        .unwrap_or_else(|e| panic!("cannot write {}: {e}", out_path.display()));
}

fn capitalize(s: &str) -> String {
    let mut chars = s.chars();
    match chars.next() {
        None => String::new(),
        Some(f) => f.to_uppercase().collect::<String>() + chars.as_str(),
    }
}

// Content of the generated widgets/types.ts file.
const BASE_TYPES: &str = "// Automatically generated by build/codegen/typescript.rs. DO NOT EDIT.\n\
\n\
export class Color {\n\
  r: u8; g: u8; b: u8;\n\
  constructor(r: u8, g: u8, b: u8) { this.r = r; this.g = g; this.b = b; }\n\
  static readonly WHITE: Color = new Color(255, 255, 255);\n\
  static readonly BLACK: Color = new Color(0, 0, 0);\n\
}\n\
\n\
export class Point {\n\
  x: u32; y: u32;\n\
  constructor(x: u32, y: u32) { this.x = x; this.y = y; }\n\
}\n\
\n\
export class Size {\n\
  width: u32; height: u32;\n\
  constructor(width: u32, height: u32) { this.width = width; this.height = height; }\n\
}\n\
\n\
export class Rect {\n\
  x: u32; y: u32; width: u32; height: u32;\n\
  constructor(x: u32, y: u32, width: u32, height: u32) { this.x = x; this.y = y; this.width = width; this.height = height; }\n\
}\n\
\n\
export class Duration {\n\
  ticks: u64;\n\
  constructor(ticks: u64) { this.ticks = ticks; }\n\
  static fromMs(ms: u64): Duration { return new Duration(ms * 1000); }\n\
  static fromSec(s: u64): Duration { return new Duration(s * 1_000_000); }\n\
  static fromMin(m: u64): Duration { return new Duration(m * 60_000_000); }\n\
}\n";
