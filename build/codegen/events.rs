use std::path::Path;

use crate::codegen::model::{EventVariantDef, EventsDef};
use crate::codegen::render;

// ── Rust bindings ─────────────────────────────────────────────────────────────

/// Map an ABI scalar type to the Rust type used in the accessor signature.
/// Pointers ("usize") use the buffer-copy protocol instead.
fn rust_abi_ty(ty: &str) -> &'static str {
    match ty {
        "u64" => "u64",
        "i32" => "i32",
        "i64" => "i64",
        _ => "u32",
    }
}

/// Generate `{out_dir}/event_wasm_bindings.rs`.
///
/// One accessor per ABI field: scalars are returned directly (host serializes
/// via rust_to_abi); pointer fields become a copy function that writes the
/// bytes into a guest-provided buffer.
pub fn generate_rust(events: &EventsDef, out_dir: &Path) {
    let mut functions = render_poll(events);
    for v in &events.variants {
        for f in &v.fields {
            let value = format!("*{}", f.name);
            for (a, e) in f.expansion.abi.iter().zip(&f.expansion.rust_to_abi.exprs) {
                let extract = render(e, &[("v", &value)]);
                functions.push_str(&if a.ty == "usize" {
                    render_copy_accessor(v, &f.name, &a.name, &extract)
                } else {
                    render_scalar_accessor(v, &f.name, &a.name, &extract, rust_abi_ty(a.ty))
                });
            }
        }
    }

    let buf = render(
        r#"// AUTO-GENERATED by build/codegen/events.rs — DO NOT EDIT.
// Source: src/widget/mod.rs WidgetEvent enum

impl HostModule for EventModule {
    fn name(&self) -> &str { "event" }

    fn register(
        &self,
        linker: &mut Linker<WasmCtx>,
        store: &mut Store<WasmCtx>,
    ) -> Result<(), wasmi::Error> {
%functions%
        Ok(())
    }
}
"#,
        &[("functions", &functions)],
    );

    let out_path = out_dir.join("event_wasm_bindings.rs");
    std::fs::write(&out_path, &buf)
        .unwrap_or_else(|e| panic!("cannot write {}: {e}", out_path.display()));
}

fn render_poll(events: &EventsDef) -> String {
    let arms: String = events.variants.iter()
        .map(|v| format!(
            "                            crate::widget::WidgetEvent::{} {{ .. }} => {},\n",
            v.name, v.index,
        ))
        .collect();

    render(
        r#"
        // --- poll ---
        linker.define(
            self.name(),
            "poll",
            wasmi::Func::wrap(
                &mut *store,
                |mut caller: Caller<'_, WasmCtx>| -> i32 {
                    let ctx = caller.data_mut();
                    let next = match ctx.event_cursor {
                        None => 0,
                        Some(i) => i + 1,
                    };
                    if next < ctx.event_queue.len() {
                        ctx.event_cursor = Some(next);
                        match &ctx.event_queue[next] {
%arms%                        }
                    } else {
                        -1
                    }
                },
            ),
        )?;"#,
        &[("arms", &arms)],
    )
}

fn render_scalar_accessor(
    variant: &EventVariantDef,
    field_name: &str,
    abi_name: &str,
    extract: &str,
    ret_ty: &str,
) -> String {
    let func_name = format!("poll_get_{}_{abi_name}", to_snake_case(&variant.name));
    render(
        r#"
        // --- %func_name% ---
        linker.define(
            self.name(),
            "%func_name%",
            wasmi::Func::wrap(
                &mut *store,
                |mut caller: Caller<'_, WasmCtx>| -> %ret_ty% {
                    let ctx = caller.data_mut();
                    if let Some(idx) = ctx.event_cursor {
                        if let Some(crate::widget::WidgetEvent::%variant% { %field%, .. }) = ctx.event_queue.get(idx) {
                            return %extract%;
                        }
                    }
                    0
                },
            ),
        )?;"#,
        &[
            ("func_name", &func_name),
            ("variant",   &variant.name),
            ("field",     field_name),
            ("extract",   extract),
            ("ret_ty",    ret_ty),
        ],
    )
}

fn render_copy_accessor(
    variant: &EventVariantDef,
    field_name: &str,
    abi_name: &str,
    bytes_expr: &str,
) -> String {
    let func_name = format!("poll_get_{}_{abi_name}", to_snake_case(&variant.name));
    render(
        r#"
        // --- %func_name% ---
        linker.define(
            self.name(),
            "%func_name%",
            wasmi::Func::wrap(
                &mut *store,
                |mut caller: Caller<'_, WasmCtx>, ptr: u32| -> Result<(), wasmi::Error> {
                    let bytes: alloc::vec::Vec<u8> = {
                        let ctx = caller.data_mut();
                        if let Some(idx) = ctx.event_cursor {
                            if let Some(crate::widget::WidgetEvent::%variant% { %field%, .. }) = ctx.event_queue.get(idx) {
                                %bytes_expr%
                            } else { return Ok(()); }
                        } else { return Ok(()); }
                    };
                    let memory = match caller.get_export("memory") {
                        Some(wasmi::Extern::Memory(m)) => m,
                        _ => return Err(wasmi::Error::new("guest memory export missing")),
                    };
                    memory.write(&mut caller, ptr as usize, &bytes)
                        .map_err(|_| wasmi::Error::new("out-of-bounds guest pointer in %func_name%"))?;
                    Ok(())
                },
            ),
        )?;"#,
        &[
            ("func_name",  &func_name),
            ("variant",    &variant.name),
            ("field",      field_name),
            ("bytes_expr", bytes_expr),
        ],
    )
}

// ── TypeScript bindings ───────────────────────────────────────────────────────

/// Generate `widgets/events.ts`.
pub fn generate_ts(events: &EventsDef, out_path: &Path) {
    let ns_decls: String = events.variants.iter()
        .flat_map(|v| {
            let snake = to_snake_case(&v.name);
            v.fields.iter().flat_map(move |f| {
                let snake = snake.clone();
                f.expansion.abi.iter().map(move |a| {
                    let fn_name = format!("poll_get_{snake}_{}", a.name);
                    if a.ty == "usize" {
                        format!("  @external(\"event\", \"{fn_name}\")\n  function {fn_name}(ptr: usize): void;\n")
                    } else {
                        format!("  @external(\"event\", \"{fn_name}\")\n  function {fn_name}(): {};\n", a.ty)
                    }
                })
            })
        })
        .collect();

    let constants: String = events.variants.iter()
        .map(|v| format!("export const EVENT_{}: i32 = {};\n", to_screaming_snake(&v.name), v.index))
        .collect();

    let event_classes: String = events.variants.iter()
        .map(render_event_class)
        .collect();

    let poll_branches: String = events.variants.iter()
        .map(render_poll_branch)
        .collect();

    let buf = render(
        r#"// AUTO-GENERATED by build/codegen/events.rs — DO NOT EDIT.

declare namespace event {
  @external("event", "poll")
  function poll(): i32;
%ns_decls%}

%constants%
export abstract class WidgetEvent {
  readonly type: i32;
  constructor(type: i32) { this.type = type; }
}

%event_classes%// Poll the next event from the queue and reconstruct it as a typed object.
// Returns null when there are no more events.
export function pollEvent(): WidgetEvent | null {
  const type = event.poll();
%poll_branches%  return null;
}
"#,
        &[
            ("ns_decls",      &ns_decls),
            ("constants",     &constants),
            ("event_classes", &event_classes),
            ("poll_branches", &poll_branches),
        ],
    );

    std::fs::write(out_path, &buf)
        .unwrap_or_else(|e| panic!("cannot write {}: {e}", out_path.display()));
}

fn render_event_class(variant: &EventVariantDef) -> String {
    let class_name = format!("{}Event", variant.name);
    let const_name = to_screaming_snake(&variant.name);

    let field_decls: String = variant.fields.iter()
        .map(|f| {
            let field_ts = to_lower_camel_case(&f.name);
            format!("  readonly {field_ts}: {};\n", f.expansion.ta_type)
        })
        .collect();

    let ctor_params = variant.fields.iter()
        .map(|f| format!("{}: {}", to_lower_camel_case(&f.name), f.expansion.ta_type))
        .collect::<Vec<_>>()
        .join(", ");

    let ctor_assigns: String = variant.fields.iter()
        .map(|f| {
            let ts = to_lower_camel_case(&f.name);
            format!("    this.{ts} = {ts};\n")
        })
        .collect();

    render(
        r#"export class %class_name% extends WidgetEvent {
%field_decls%  constructor(%ctor_params%) {
    super(EVENT_%const_name%);
%ctor_assigns%  }
}

"#,
        &[
            ("class_name",   &class_name),
            ("field_decls",  &field_decls),
            ("ctor_params",  &ctor_params),
            ("const_name",   &const_name),
            ("ctor_assigns", &ctor_assigns),
        ],
    )
}

fn render_poll_branch(variant: &EventVariantDef) -> String {
    let snake = to_snake_case(&variant.name);
    let class_name = format!("{}Event", variant.name);
    let const_name = to_screaming_snake(&variant.name);

    // Materialize each ABI field as a local variable: scalars are read
    // directly; pointer fields allocate a buffer sized by the matching
    // `*_len` field (declared earlier by ABI order) and ask the host to
    // fill it. The ctor args then deserialize via abi_to_ts.
    let mut field_reads = String::new();
    for f in &variant.fields {
        for a in &f.expansion.abi {
            let fn_name = format!("poll_get_{snake}_{}", a.name);
            if a.ty == "usize" {
                let len_name = format!("{}_len", a.name.trim_end_matches("_ptr"));
                field_reads.push_str(&render(
                    r#"    const %ptr%_buf = new ArrayBuffer(%len%);
    const %ptr% = changetype<usize>(%ptr%_buf);
    event.%fn%(%ptr%);
"#,
                    &[("ptr", &a.name), ("len", &len_name), ("fn", &fn_name)],
                ));
            } else {
                field_reads.push_str(&format!("    const {} = event.{fn_name}();\n", a.name));
            }
        }
        field_reads.push_str(&f.expansion.abi_to_ts.preamble);
    }

    let ctor_args = variant.fields.iter()
        .map(|f| f.expansion.abi_to_ts.exprs[0].clone())
        .collect::<Vec<_>>()
        .join(", ");

    render(
        r#"  if (type == EVENT_%const_name%) {
%field_reads%    return new %class_name%(%ctor_args%);
  }
"#,
        &[
            ("const_name",  &const_name),
            ("field_reads", &field_reads),
            ("class_name",  &class_name),
            ("ctor_args",   &ctor_args),
        ],
    )
}

// ── case helpers ─────────────────────────────────────────────────────────────

fn to_lower_camel_case(s: &str) -> String {
    let camel = to_camel_case(s);
    let mut chars = camel.chars();
    match chars.next() {
        None => String::new(),
        Some(f) => f.to_ascii_lowercase().to_string() + chars.as_str(),
    }
}

fn to_snake_case(s: &str) -> String {
    let mut result = String::new();
    for (i, c) in s.chars().enumerate() {
        if c.is_uppercase() && i > 0 { result.push('_'); }
        result.push(c.to_ascii_lowercase());
    }
    result
}

fn to_screaming_snake(s: &str) -> String {
    let mut result = String::new();
    for (i, c) in s.chars().enumerate() {
        if c.is_uppercase() && i > 0 { result.push('_'); }
        result.push(c.to_ascii_uppercase());
    }
    result
}

fn to_camel_case(s: &str) -> String {
    s.split('_')
        .map(|w| {
            let mut c = w.chars();
            match c.next() {
                None => String::new(),
                Some(f) => f.to_uppercase().collect::<String>() + c.as_str(),
            }
        })
        .collect()
}
